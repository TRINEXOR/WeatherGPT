// Helper to flatten all cities
export const ALL_INDIAN_CITIES: WeatherLocation[] = ALL_INDIAN_STATES_AND_UTS.flatMap(s => s.cities);

// Fast local search over all Indian cities and states
export function searchIndianLocations(query: string): WeatherLocation[] {
  if (!query || query.trim().length === 0) return [];
  const q = query.toLowerCase().trim();

  // Match state/UT names, city names, or admin regions
  const matched: WeatherLocation[] = [];
  const addedKeys = new Set<string>();

  for (const state of ALL_INDIAN_STATES_AND_UTS) {
    const stateMatches = state.name.toLowerCase().includes(q) || state.code.toLowerCase() === q;

    for (const city of state.cities) {
      const cityKey = `${city.name}-${city.latitude}-${city.longitude}`;
      if (addedKeys.has(cityKey)) continue;

      if (
        city.name.toLowerCase().includes(q) ||
        (city.admin1 && city.admin1.toLowerCase().includes(q)) ||
        stateMatches
      ) {
        matched.push(city);
        addedKeys.add(cityKey);
      }
    }
  }

  return matched;
}
